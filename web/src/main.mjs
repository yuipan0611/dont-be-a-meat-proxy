import { readFile } from 'node:fs/promises';
import pg from 'pg';
import { createApp } from './server.mjs';
import { createData } from './data.mjs';
const required = k => { if(!process.env[k]) throw new Error(`missing ${k}`); return process.env[k]; };
const secret = async k => (await readFile(required(k),'utf8')).trim();
const generated=JSON.parse(await readFile(new URL('../.generated/architecture.json',import.meta.url),'utf8'));
const configured=process.env.WEB_MAP_FILE?JSON.parse(await readFile(process.env.WEB_MAP_FILE,'utf8')):{};
if(configured.repo && configured.repo!==generated.repo)throw new Error('map and code snapshot repo mismatch');
const map={...generated,...configured,symbols:generated.symbols,atlas:generated.atlas,codeSnapshot:generated.codeSnapshot};
const origin=required('WEB_ORIGIN');
if (new URL(origin).protocol !== 'https:' || new URL(origin).origin !== origin) throw new Error('WEB_ORIGIN must be an HTTPS origin without trailing slash');
if (!/^[\w.-]+\/[\w.-]+$/.test(map.repo)) throw new Error('invalid configured repo');
const pool=new pg.Pool({host:required('HUB_PG_HOST'),database:'hub',user:required('HUB_PG_USER'),password:await secret('HUB_PG_PASSWORD_FILE'),max:3,connectionTimeoutMillis:5000,statement_timeout:8000});
pool.on('error',()=>process.stderr.write('web database connection error\n'));
const tokenText=await secret('MAIL_TOKEN_FILE');
const token=tokenText.match(/^HTTP_BEARER_TOKEN=([A-Za-z0-9_-]{32,128})$/m)?.[1] ?? tokenText;
const data=createData({pool,map,mailConfig:{url:required('MAIL_URL'),token,projectKey:required('MAIL_PROJECT_KEY'),agentName:'HubGuide',groupId:required('WEB_GROUP_ID'),guildId:required('DISCORD_GUILD_ID')},githubToken:process.env.GITHUB_TOKEN_FILE?await secret('GITHUB_TOKEN_FILE'):null});
const server=createApp({data,map,origin,clientId:required('DISCORD_APPLICATION_ID'),clientSecret:await secret('DISCORD_CLIENT_SECRET_FILE')});
server.listen(8080,'0.0.0.0',()=>console.log('project guide listening on 8080'));
for(const signal of ['SIGTERM','SIGINT']) process.once(signal,()=>server.close(async()=>{await pool.end();process.exit(0);}));
